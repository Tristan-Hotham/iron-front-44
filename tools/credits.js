// Writes CREDITS.md from the track and sound lists in src/music.js.  Run: node tools/credits.js
const fs = require('fs'), path = require('path');
const root = path.join(__dirname, '..');
const src = fs.readFileSync(path.join(root, 'src', 'music.js'), 'utf8');
const tracks = src.split('\n').filter(l => /^\s*\{file:'/.test(l)).map(l => Function('return ' + l.trim().replace(/,$/, ''))());
const sfx = Function('return ' + src.slice(src.indexOf('[', src.indexOf('SFX_CREDITS')), src.indexOf('];', src.indexOf('SFX_CREDITS')) + 1))();
// the recorded library in sfx/ (tools/sfx-sources.json): also written out as src/sfx-credits.js for the in-game Credits screen
const lib = JSON.parse(fs.readFileSync(path.join(__dirname, 'sfx-sources.json'), 'utf8').replace(/^﻿/, ''));
const clean = t => t.replace(/\.(wav|mp3|flac|ogg|aif)$/i, '');
fs.writeFileSync(path.join(root, 'src', 'sfx-credits.js'), '/* generated by tools/credits.js from tools/sfx-sources.json: the sound library and its licences */\nconst SFX_LIB_CREDITS = ' +
  JSON.stringify(lib.map(s => [clean(s.title), `${s.user}, Freesound #${s.id}`, s.lic]), null, 0).replace(/\],\[/g, '],\n  [') + ';\n');
sfx.push(...lib.map(s => [`${clean(s.title)} (sfx/${s.file})`, `${s.user}, [Freesound #${s.id}](https://freesound.org/s/${s.id}/)`, s.lic]));
const md = [
  '# Credits', '',
  'The game code is MIT-licensed (see LICENSE). The music and recorded sounds are not covered by that licence: each is public domain or used under the licence named below. The music and the first three sounds come from Wikimedia Commons; the rest of the sound library comes from Freesound (CC0 or CC BY only).', '',
  `## Music (${tracks.length} tracks, in \`music/\`)`, '',
  '| File | Title | Composer · performers | Licence |', '| --- | --- | --- | --- |',
  ...tracks.map(t => `| ${t.file} | ${t.title} | ${t.by} | ${t.lic} |`), '',
  '## Recorded sound (in `sfx/`)', '',
  '| Sound | Source | Licence |', '| --- | --- | --- |',
  ...sfx.map(([a, b, c]) => `| ${a} | ${b} | ${c} |`), '',
  '"Duet Musette" by Kevin MacLeod (incompetech.com), licensed under Creative Commons: By Attribution 3.0. CC BY-SA recordings were re-encoded to mono Opus for size; those adaptations are shared under the same licence. Freesound sounds are the site\'s 128 kbps MP3 previews, used whole; the game cuts them into takes and varies their pitch as it plays them.', '',
];
fs.writeFileSync(path.join(root, 'CREDITS.md'), md.join('\n'));
console.log(`CREDITS.md: ${tracks.length} tracks, ${sfx.length} sounds`);
