# Turns an AI tester report (reports/<name>.txt) into src/difficulty.js:
# the share of games the computer won playing the player's side, per battle.
param([string]$Report = 'all3')
$root = Split-Path $PSScriptRoot -Parent
$lines = Get-Content (Join-Path $root "reports\$Report.txt")
$pairs = foreach ($l in $lines) { if ($l -match '^(\w+)\s+(?:[WL]\d+\s+){5,8}(\d+)%') { "  $($Matches[1]):$([double]$Matches[2] / 100)" } }
$js = "/* generated by tools/difficulty.ps1 from reports/$Report.txt: AI tester win rates for side 1 */`nObject.assign(DIFFICULTY, {`n" + ($pairs -join ",`n") + "`n});`n"
[IO.File]::WriteAllText((Join-Path $root 'src\difficulty.js'), $js, (New-Object Text.UTF8Encoding $false))
"wrote $($pairs.Count) entries"
